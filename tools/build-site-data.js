#!/usr/bin/env node
/* Generates src/site-resources.js (ES module for the Worker's public pages) from the in-game help contacts in
   js/data/resources.js and their zh-SG translations in i18n/zh-SG/misc.js, so the public Disclaimer page can never
   drift from the game. Usage: node tools/build-site-data.js [--check]  (--check exits 1 if the file is stale). */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'site-resources.js');

const sandbox = { window: {}, localStorage: undefined };
sandbox.window.I18N = { 'zh-SG': { text: {} } };
vm.createContext(sandbox);
vm.runInContext('var window = this.window;', sandbox);
vm.runInContext(fs.readFileSync(path.join(root, 'js/data/resources.js'), 'utf8'), sandbox);
vm.runInContext(fs.readFileSync(path.join(root, 'i18n/zh-SG/misc.js'), 'utf8'), sandbox);
const SG = sandbox.window.RESOURCE_CONTACTS['en-SG'];
const zh = sandbox.window.I18N['zh-SG'].text;
const verified = Object.values(sandbox.window.RESOURCES_BY_LOCALE['en-SG'])[0].verified;
const rows = Object.entries(SG).map(([id, c]) => {
  const en = `${c.name}: ${c.how} (${c.hours})`;
  if (!zh[en]) throw new Error(`No zh-SG translation for help contact "${id}": ${en}`);
  return { id, en, zh: zh[en], src: c.src };
});
const body = `/* GENERATED by tools/build-site-data.js from js/data/resources.js + i18n/zh-SG/misc.js. Do not edit by hand. */
export const RESOURCES_VERIFIED = ${JSON.stringify(verified)};
export const RESOURCES = ${JSON.stringify(rows, null, 2)};
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('src/site-resources.js is stale: run node tools/build-site-data.js'); process.exit(1); }
  console.log(`site resources up to date (${rows.length} contacts, verified ${verified})`);
} else {
  fs.writeFileSync(out, body);
  console.log(`wrote ${path.relative(root, out)} (${rows.length} contacts, verified ${verified})`);
}
