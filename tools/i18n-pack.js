#!/usr/bin/env node
/* Translation workflow helper for locale packs keyed by the English source string.
   node tools/i18n-pack.js dump <group> [--all]    -> "index|English" lines (newlines as \n), untranslated only unless --all
   node tools/i18n-pack.js put <group> <file>      -> merge "index|translation" lines into i18n/zh-SG/<group>.js (source)
   node tools/i18n-pack.js status                  -> coverage per group
   node tools/i18n-pack.js bundle                  -> rebuild js/i18n/zh-SG.text.js (the single file the game loads)
   `put` rebuilds the bundle automatically. The per-group sources are not deployed (see .assetsignore).
   Groups come from tools/i18n-extract.js (--groups). */
const fs = require('fs');
const path = require('path');
const { collect } = require('./i18n-extract.js');
const LOC = 'zh-SG';
const dir = path.join(__dirname, '..', 'i18n', LOC);
const bundleFile = path.join(__dirname, '..', 'js', 'i18n', `${LOC}.text.js`);
const groups = collect(true);
const fileOf = (g) => path.join(dir, `${g}.js`);
const read = (g) => {
  const f = fileOf(g);
  if (!fs.existsSync(f)) return {};
  const src = fs.readFileSync(f, 'utf8');
  const json = src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1);
  return JSON.parse(json);
};
const write = (g, map) => {
  const body = JSON.stringify(map, null, 1).replace(/^ "/gm, '  "');
  fs.writeFileSync(fileOf(g), `/* ${LOC} translations for "${g}" (generated by tools/i18n-pack.js; keys are the English source). */\n`
    + `Object.assign(window.I18N['${LOC}'].text, ${body});\n`);
};
const bundle = () => {
  const all = {};
  for (const g of groups) Object.assign(all, read(g.name));
  fs.writeFileSync(bundleFile, `/* ${LOC} story and data text, keyed by the English source. Generated by tools/i18n-pack.js bundle from i18n/${LOC}/; do not edit by hand. */\n`
    + `Object.assign(window.I18N['${LOC}'].text, ${JSON.stringify(all)});\n`);
  return Object.keys(all).length;
};
const ph = (s) => (s.match(/\{[^}]+\}/g) || []).sort().join(' ');
const [cmd, gname, file] = process.argv.slice(2);
const G = groups.find((g) => g.name === gname);
if (cmd === 'dump') {
  const have = read(gname);
  G.strings.forEach((s, i) => { if (process.argv.includes('--all') || !have[s]) console.log(`${i}|${s.replace(/\n/g, '\\n')}`); });
} else if (cmd === 'put') {
  const map = read(gname);
  let n = 0;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^(\d+)\|(.*)$/);
    if (!m) { if (line.trim()) console.warn('skip:', line.slice(0, 60)); continue; }
    const en = G.strings[+m[1]];
    if (!en) { console.warn('no string #' + m[1]); continue; }
    const zh = m[2].replace(/\\n/g, '\n').trim();
    if (ph(en) !== ph(zh)) console.warn(`placeholder mismatch #${m[1]}: [${ph(en)}] vs [${ph(zh)}]`);
    if ((en.match(/\n/g) || []).length !== (zh.match(/\n/g) || []).length) console.warn(`line-break mismatch #${m[1]}`);
    map[en] = zh; n++;
  }
  const ordered = {};
  G.strings.forEach((s) => { if (map[s]) ordered[s] = map[s]; });
  Object.keys(map).forEach((k) => { if (!(k in ordered)) console.warn('stale key dropped:', k.slice(0, 60)); });
  write(gname, ordered);
  bundle();
  console.log(`${gname}: +${n}, ${Object.keys(ordered).length}/${G.strings.length}`);
} else if (cmd === 'bundle') {
  console.log('bundled', bundle(), 'strings ->', path.relative(process.cwd(), bundleFile));
} else {
  let t = 0, d = 0;
  for (const g of groups) { const h = read(g.name); const k = g.strings.filter((s) => h[s]).length; t += g.strings.length; d += k; console.log(g.name.padEnd(16), `${k}/${g.strings.length}`); }
  console.log('total', `${d}/${t}`);
}
